def get_demo_delivery_id(user_id: int) -> int | None:
    with sqlite3.connect(db.DB_PATH) as conn:
        row = conn.execute(
            'SELECT id FROM deliveries WHERE user_id = ? ORDER BY id LIMIT 1', (user_id,)
        ).fetchone()
    return int(row[0]) if row else None


def update_demo_delivery(delivery_id: int, customer_name: str, markdown: str) -> None:
    with sqlite3.connect(db.DB_PATH) as conn:
        conn.execute(
            'UPDATE deliveries SET customer_name = ?, markdown = ? WHERE id = ?',
            (customer_name, markdown, delivery_id),
        )


def main() -> None:
    db.init_db()
    password_hash: str | None = None
    user_ids: list[int] = []
    created_users = 0
    created_deliveries = 0

    for username, *_ in DEMO_PROFILES:
        user = db.get_user_by_username(username)
        if user is None:
            if password_hash is None:
                password_hash = hash_password('demo123456')
            role = 'admin' if username in DEMO_ADMIN_USERNAMES else 'user'
            user_id = db.create_user(username, password_hash, role=role)
            created_users += 1
        else:
            user_id = user['id']
        user_ids.append(user_id)

    for profile, user_id in zip(DEMO_PROFILES, user_ids):
        customer_name = profile[1]
        markdown = build_markdown(profile)
        existing = get_demo_delivery_id(user_id)
        if existing is not None:
            update_demo_delivery(existing, customer_name, markdown)
        else:
            session_id = db.create_session(user_id, {})
            db.create_delivery(session_id, user_id, customer_name, markdown)
            created_deliveries += 1

    print(f'新增用户 {created_users} 个，新增交付物 {created_deliveries} 个。')


if __name__ == '__main__':
    main()
